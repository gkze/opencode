import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync, appendFileSync, existsSync } from "node:fs"
import path from "node:path"

const git = (...args) =>
  execFileSync("git", args, {
    encoding: "utf8",
    // Only branch pushes need workflow-write access. Keep credentials out of argv
    // and leave release tag creation on the built-in token to avoid duplicate runs.
    env:
      args[0] === "push" && process.env.FORK_PUSH_TOKEN
        ? {
            ...process.env,
            GIT_CONFIG_COUNT: "2",
            GIT_CONFIG_KEY_0: "http.https://github.com/.extraheader",
            GIT_CONFIG_VALUE_0: "",
            GIT_CONFIG_KEY_1: "http.https://github.com/.extraheader",
            GIT_CONFIG_VALUE_1: `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${process.env.FORK_PUSH_TOKEN}`).toString("base64")}`,
          }
        : process.env,
  }).trim()
const lines = (text) => (text ? text.split("\n") : [])
const read = (file) => JSON.parse(readFileSync(file, "utf8"))
const sha = (value) => {
  assert.match(value, /^[0-9a-f]{40}$/)
  return value
}
const controls = [
  ".github/workflows",
  ".github/actions",
  ".github/aw",
  "script/fork/nightly.mjs",
  "script/fork/publish.mjs",
  "script/fork/version.mjs",
]
// `bun.lock` is derived from package.json: replaying a lockfile commit turns every upstream
// dependency bump into a text conflict. These commits are regenerated by `relock` instead.
const derivedSubject = "chore(deps): regenerate fork lockfile"
const isDerived = (commit) =>
  execFileSync("git", ["show", "-s", "--format=%s", commit], { encoding: "utf8" }).trim() === derivedSubject
const split = (commits) => ({ patches: commits.filter((c) => !isDerived(c)), derived: commits.filter(isDerived) })
const stack = (input) => [...input.commits, ...(input.derived ?? [])].sort()
const gitIn = (cwd, ...args) =>
  execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim()
// `bun.lock` is derived state. Materialize it so the canonical frozen install always
// sees a lockfile that matches the replayed package.json, including after a text
// conflict stopped `replay` before it could derive one.
const materializeLockfile = () => {
  if (!existsSync("bun.lock")) return
  execFileSync("bun", ["install", "--lockfile-only"], { stdio: "inherit" })
  if (!git("status", "--porcelain", "--", "bun.lock")) return
  git("add", "bun.lock")
  git("commit", "-m", derivedSubject)
}
const branch = "refs/heads/gkze/patches"
const verifyCandidate = (input, candidate, directory) => {
  assert.deepEqual(stack(input), lines(git("rev-list", "--reverse", `${input.upstream}..${input.old}`)).sort())
  git("merge-base", "--is-ancestor", input.upstream, candidate)
  assert.equal(
    git("rev-list", "--merges", `${input.upstream}..${candidate}`),
    "",
    "Candidate must be a linear patch stack",
  )
  const base = git("merge-base", input.old, input.upstream)
  for (const file of lines(git("diff", "--name-only", input.old, candidate, "--", ...controls))) {
    // Carry upstream-only control changes, but never accept agent-authored workflows.
    assert.equal(git("diff", "--name-only", base, input.old, "--", file), "", `Fork control conflict: ${file}`)
    assert.equal(
      git("diff", "--name-only", input.upstream, candidate, "--", file),
      "",
      `Publication control changed: ${file}`,
    )
  }
  const report = read(path.join(directory, "report.json"))
  assert.ok(typeof report.summary === "string" && report.summary.trim())
  assert.ok(
    Array.isArray(report.tests) && report.tests.length && report.tests.every((x) => typeof x === "string" && x.trim()),
  )
  // A candidate that follows a failed publication fails the same way unless the review dealt with the cause.
  const publish = path.join(directory, "publish.json")
  if (existsSync(publish) && !["success", "none"].includes(read(publish).conclusion))
    assert.ok(
      typeof report.publish === "string" && report.publish.trim(),
      "The report must address the failed publication",
    )
  assert.ok(Array.isArray(report.patches))
  assert.deepEqual(
    report.patches.map((p) => p.old).sort(),
    [...input.commits].sort(),
    "Every old patch needs exactly one decision",
  )
  const mapped = report.patches.flatMap((p) => {
    assert.ok(["keep", "adapt", "drop"].includes(p.action))
    assert.ok(typeof p.reason === "string" && p.reason.trim())
    assert.ok(Array.isArray(p.commits))
    assert.equal(p.commits.length === 0, p.action === "drop")
    return p.commits.map(sha)
  })
  const candidateCommits = lines(git("rev-list", `${input.upstream}..${candidate}`))
  const candidateSet = new Set(candidateCommits)
  assert.ok(mapped.every((commit) => candidateSet.has(commit)), "Review references a commit outside candidate history")
  for (const commit of candidateCommits.filter(isDerived)) {
    // The replay materializes the lockfile; that commit is ours, so it has no review entry.
    assert.deepEqual(lines(git("diff", "--name-only", `${commit}^`, commit)), ["bun.lock"], "Derived commit may only update bun.lock")
  }
  assert.deepEqual(
    [...new Set(mapped.filter((commit) => !isDerived(commit)))].sort(),
    candidateCommits.filter((commit) => !isDerived(commit)).sort(),
    "Every new commit needs provenance",
  )
}

const [command, directory] = process.argv.slice(2)

if (command === "prepare") {
  mkdirSync(directory, { recursive: true })
  git("fetch", "https://github.com/anomalyco/opencode.git", "dev")
  const upstream = git("rev-parse", "FETCH_HEAD")
  const old = git("rev-parse", "HEAD")
  const commits = lines(git("rev-list", "--reverse", `${upstream}..${old}`))
  const { patches, derived } = split(commits)
  const input = { old, upstream, commits: patches, derived }
  writeFileSync(path.join(directory, "input.json"), JSON.stringify(input, null, 2))
} else if (command === "replay") {
  const input = read(path.join(directory, "input.json"))
  assert.equal(git("rev-parse", "HEAD"), sha(input.old))
  assert.equal(git("status", "--porcelain"), "", "Replay requires a clean checkout")
  assert.deepEqual(stack(input), lines(git("rev-list", "--reverse", `${sha(input.upstream)}..${input.old}`)).sort())
  assert.equal(git("rev-list", "--merges", `${input.upstream}..${input.old}`), "", "Expected a linear patch stack")
  git("checkout", "-b", "nightly-candidate", input.upstream)
  const patches = []
  for (const old of input.commits) {
    const result = spawnSync("git", ["cherry-pick", "--no-gpg-sign", "--keep-redundant-commits", old], {
      encoding: "utf8",
    })
    if (result.status === 0) {
      patches.push({ old, commit: git("rev-parse", "HEAD") })
      continue
    }
    const conflicts = lines(git("diff", "--name-only", "--diff-filter=U"))
    assert.ok(conflicts.length, result.stderr || "Cherry-pick failed without a resolvable conflict")
    git("cherry-pick", "--abort")
    assert.ok(
      !conflicts.some((file) => controls.some((control) => file === control || file.startsWith(`${control}/`))),
      `Publication control conflict: ${conflicts.join(", ")}`,
    )
    writeFileSync(
      path.join(directory, "replay.json"),
      JSON.stringify({ patches, pending: input.commits.slice(patches.length), conflicts }, null, 2),
    )
    process.exit(0)
  }
  // Replay is mechanical evidence, never a substitute for the semantic review report.
  // The lockfile is derived state: materialize it here so the canonical frozen install the
  // reviewing agent runs next has a lockfile that matches the replayed package.json.
  materializeLockfile()
  writeFileSync(path.join(directory, "replay.json"), JSON.stringify({ patches, pending: [], conflicts: [] }, null, 2))
} else if (command === "verify") {
  const input = read(path.join(directory, "input.json"))
  const candidate = git("rev-parse", "refs/heads/nightly-candidate")
  assert.equal(git("rev-parse", "HEAD"), candidate, "Review must describe the checked out candidate")
  assert.equal(git("status", "--porcelain"), "", "Review requires a clean committed candidate")
  verifyCandidate(input, candidate, directory)
  console.log(`Verified candidate and complete report: ${candidate}`)
} else if (command === "accept") {
  const input = read(path.join(directory, "input.json"))
  assert.equal(sha(input.old), sha(process.env.SOURCE_SHA))
  git("fetch", "https://github.com/anomalyco/opencode.git", "dev")
  git("merge-base", "--is-ancestor", sha(input.upstream), "FETCH_HEAD")
  git("bundle", "verify", path.join(directory, "candidate.bundle"))
  git("fetch", path.join(directory, "candidate.bundle"), "refs/heads/nightly-candidate")
  const candidate = git("rev-parse", "FETCH_HEAD")
  verifyCandidate(input, candidate, directory)
  const staging = `refs/heads/nightly-${process.env.GITHUB_RUN_ID}`
  assert.match(staging, /^refs\/heads\/nightly-\d+$/)
  git("push", "origin", `${candidate}:${staging}`)
  appendFileSync(process.env.GITHUB_OUTPUT, `candidate=${candidate}\nold=${input.old}\nupstream=${input.upstream}\n`)
} else if (command === "lockfile") {
  // A text conflict stops `replay` before it derives the lockfile. The trusted post-step
  // derives it here, after the agent finished the replay and before install-dependent
  // validation, so a conflicted candidate can never dead-end on a stale `bun.lock`.
  materializeLockfile()
  // Prove the derived lockfile resolves reproducibly before validation and export.
  execFileSync("bun", ["install", "--frozen-lockfile", "--ignore-scripts"], { stdio: "inherit" })
} else if (command === "relock") {
  // package.json is the authority for the dependency graph and bun.lock is derived from it,
  // so regenerate the lockfile here with the candidate's own pinned Bun. A dependency bump
  // upstream then costs a commit instead of a text conflict the reviewing agent must refuse.
  const candidate = sha(process.env.FORK_CANDIDATE)
  const tree = path.join(directory, "relock")
  const gitIn = (...args) => execFileSync("git", args, { cwd: tree, encoding: "utf8" }).trim()
  const bun = (...args) => execFileSync("bun", args, { cwd: tree, stdio: "inherit" })
  git("worktree", "add", "--detach", tree, candidate)
  try {
    bun("install", "--lockfile-only")
    if (gitIn("status", "--porcelain", "--", "bun.lock")) {
      gitIn("add", "bun.lock")
      gitIn(
        "-c", "commit.gpgsign=false",
        "-c", "user.name=github-actions[bot]",
        "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
        "commit", "-m", derivedSubject,
      )
    }
    const amended = gitIn("rev-parse", "HEAD")
    if (amended !== candidate) {
      // Prove the regenerated lockfile is reproducible before it can be published.
      bun("install", "--frozen-lockfile", "--ignore-scripts")
      git("push", "origin", `+${amended}:refs/heads/nightly-${process.env.GITHUB_RUN_ID}`)
    }
    appendFileSync(process.env.GITHUB_OUTPUT, `candidate=${amended}\n`)
  } finally {
    git("worktree", "remove", "--force", tree)
  }
} else if (command === "promote") {
  const old = sha(process.env.FORK_OLD)
  const candidate = sha(process.env.FORK_CANDIDATE)
  const upstream = sha(process.env.FORK_UPSTREAM)
  git("fetch", "origin", candidate, old)
  git("merge-base", "--is-ancestor", upstream, candidate)
  const current = git("ls-remote", "origin", branch).split("\t")[0]
  // Retrying publication after a successful promotion must not overwrite newer work.
  if (current !== candidate) {
    assert.equal(current, old, "Fork advanced during this nightly; retry against the new tip")
    const archive = `refs/tags/fork-backup-${old}`
    git(
      "push",
      "--atomic",
      `--force-with-lease=${branch}:${old}`,
      "origin",
      `${old}:${archive}`,
      `${candidate}:${branch}`,
    )
  }
  assert.equal(git("ls-remote", "origin", branch).split("\t")[0], candidate)
} else if (command === "feedback") {
  // The refresh never sees the publication it hands its candidate to. Record how the latest one ended, so the
  // review starts from a failure instead of reproducing it: for each failed job, the steps that did not pass and
  // how long each took, what the runner reported, and the end of its log.
  mkdirSync(directory, { recursive: true })
  const api = (endpoint) =>
    fetch(`${process.env.GITHUB_API_URL}/repos/${process.env.GITHUB_REPOSITORY}/${endpoint}`, {
      headers: { authorization: `Bearer ${process.env.GH_TOKEN}`, accept: "application/vnd.github+json" },
    })
  const json = async (endpoint) => {
    const response = await api(endpoint)
    assert.ok(response.ok, `${endpoint}: HTTP ${response.status}`)
    return response.json()
  }
  const passed = (item) => ["success", "skipped"].includes(item.conclusion)
  // Written the way the runner writes a time limit ("1h0m0s"), so the two compare at a glance.
  const took = (ms) => {
    const seconds = Math.round(ms / 1000)
    return Number.isFinite(seconds)
      ? `${Math.floor(seconds / 3600)}h${Math.floor(seconds / 60) % 60}m${seconds % 60}s`.replace(/^0h(0m)?/, "")
      : undefined
  }
  // The API reports a composite action as one step. The runner's log names each step inside one and says how it
  // ended. An action ends after the step inside it that failed, so only the innermost are kept.
  const inside = (log) => {
    const names = new Map(
      Array.from(log.matchAll(/##\[start-action display=(.*);id=(\S+)\]$/gm), (match) => [match[2], match[1]]),
    )
    return Array.from(
      log.matchAll(/##\[end-action id=(\S+);outcome=\w+;conclusion=(\w+);duration_ms=(\d+)\]$/gm),
      (match) => ({ id: match[1], conclusion: match[2], took: took(Number(match[3])) }),
    )
      .filter((step) => !passed(step))
      .filter((step, _, all) => !all.some((other) => other.id.startsWith(`${step.id}.`)))
      .map((step) => ({ name: names.get(step.id) ?? step.id, conclusion: step.conclusion, took: step.took }))
  }
  // A publication whose refresh failed is skipped before it builds anything, so it says nothing.
  const runs = await json("actions/workflows/fork-nightly-publish.yml/runs?status=completed&per_page=30")
  const run = runs.workflow_runs.find((item) => item.conclusion !== "skipped")
  const failed =
    !run || run.conclusion === "success"
      ? []
      : (await json(`actions/runs/${run.id}/jobs?per_page=100`)).jobs.filter((job) => !passed(job))
  const jobs = await Promise.all(
    failed.map(async (job) => {
      // A log expires before its run does, and nothing missing here may stop the refresh.
      const response = await api(`actions/jobs/${job.id}/logs`)
      const log = response.ok
        ? (await response.text()).replace(/\x1b\[[0-9;?]*[ -/]*[@-~]/g, "")
        : `Log unavailable: HTTP ${response.status}`
      writeFileSync(
        path.join(directory, `publish-${job.id}.log`),
        `${log.trimEnd().split("\n").slice(-200).join("\n")}\n`,
      )
      // A job is also a check run, which the runner annotates with why the job ended. Only there does it say that
      // a job ran out of time: the log of one says that it was cancelled, as it does when a person cancels it.
      const annotations = await api(`check-runs/${job.id}/annotations?per_page=100`)
      const errors = annotations.ok
        ? (await annotations.json()).filter((item) => item.annotation_level === "failure").map((item) => item.message)
        : [`Annotations unavailable: HTTP ${annotations.status}`]
      const steps = [
        ...job.steps
          .filter((step) => !passed(step))
          .map((step) => ({
            name: step.name,
            conclusion: step.conclusion,
            took: took(Date.parse(step.completed_at) - Date.parse(step.started_at)),
          })),
        ...inside(log),
      ]
      const limit = errors
        .map((error) => error.match(/exceeded the maximum execution time of (\S+)/)?.[1])
        .find(Boolean)
      // The innermost step still running when the limit stopped the job is the one that did not return.
      const stopped = steps.findLast((step) => step.conclusion === "cancelled")
      return {
        name: job.name,
        conclusion: job.conclusion,
        url: job.html_url,
        took: took(Date.parse(job.completed_at) - Date.parse(job.started_at)),
        ...(limit ? { hang: { limit, step: stopped?.name, took: stopped?.took } } : {}),
        errors,
        steps,
        log: `publish-${job.id}.log`,
      }
    }),
  )
  writeFileSync(
    path.join(directory, "publish.json"),
    JSON.stringify(
      run ? { run: run.id, url: run.html_url, conclusion: run.conclusion, jobs } : { conclusion: "none", jobs },
      null,
      2,
    ),
  )
} else {
  throw new Error("Usage: nightly.mjs prepare|replay|verify|accept|relock|feedback <directory>, lockfile, or promote")
}
