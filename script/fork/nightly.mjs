import assert from "node:assert/strict"
import { execFileSync, spawnSync } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync, appendFileSync } from "node:fs"
import path from "node:path"

const git = (...args) =>
  execFileSync("git", args, {
    encoding: "utf8",
    // Only branch pushes need workflow-write access. Keep credentials out of argv
    // and leave release tag creation on the built-in token to avoid duplicate runs.
    env:
      args[0] === "push" && process.env.FORK_PUSH_TOKEN
        ? {
            ...process.env,
            GIT_CONFIG_COUNT: "2",
            GIT_CONFIG_KEY_0: "http.https://github.com/.extraheader",
            GIT_CONFIG_VALUE_0: "",
            GIT_CONFIG_KEY_1: "http.https://github.com/.extraheader",
            GIT_CONFIG_VALUE_1: `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${process.env.FORK_PUSH_TOKEN}`).toString("base64")}`,
          }
        : process.env,
  }).trim()
const lines = (text) => (text ? text.split("\n") : [])
const read = (file) => JSON.parse(readFileSync(file, "utf8"))
const sha = (value) => {
  assert.match(value, /^[0-9a-f]{40}$/)
  return value
}
const controls = [
  ".github/workflows",
  ".github/actions",
  ".github/aw",
  "script/fork/nightly.mjs",
  "script/fork/publish.mjs",
  "script/fork/version.mjs",
]
// `bun.lock` is derived from package.json: replaying a lockfile commit turns every upstream
// dependency bump into a text conflict. These commits are regenerated by `relock` instead.
const derivedSubject = "chore(deps): regenerate fork lockfile"
const isDerived = (commit) =>
  execFileSync("git", ["show", "-s", "--format=%s", commit], { encoding: "utf8" }).trim() === derivedSubject
const split = (commits) => ({ patches: commits.filter((c) => !isDerived(c)), derived: commits.filter(isDerived) })
const stack = (input) => [...input.commits, ...(input.derived ?? [])].sort()
const gitIn = (cwd, ...args) =>
  execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim()
const branch = "refs/heads/gkze/patches"
const [command, directory] = process.argv.slice(2)

if (command === "prepare") {
  mkdirSync(directory, { recursive: true })
  git("fetch", "https://github.com/anomalyco/opencode.git", "dev")
  const upstream = git("rev-parse", "FETCH_HEAD")
  const old = git("rev-parse", "HEAD")
  const commits = lines(git("rev-list", "--reverse", `${upstream}..${old}`))
  const { patches, derived } = split(commits)
  const input = { old, upstream, commits: patches, derived }
  writeFileSync(path.join(directory, "input.json"), JSON.stringify(input, null, 2))
} else if (command === "replay") {
  const input = read(path.join(directory, "input.json"))
  assert.equal(git("rev-parse", "HEAD"), sha(input.old))
  assert.equal(git("status", "--porcelain"), "", "Replay requires a clean checkout")
  assert.deepEqual(stack(input), lines(git("rev-list", "--reverse", `${sha(input.upstream)}..${input.old}`)).sort())
  assert.equal(git("rev-list", "--merges", `${input.upstream}..${input.old}`), "", "Expected a linear patch stack")
  git("checkout", "-b", "nightly-candidate", input.upstream)
  const patches = []
  for (const old of input.commits) {
    const result = spawnSync("git", ["cherry-pick", "--no-gpg-sign", "--keep-redundant-commits", old], {
      encoding: "utf8",
    })
    if (result.status === 0) {
      patches.push({ old, commit: git("rev-parse", "HEAD") })
      continue
    }
    const conflicts = lines(git("diff", "--name-only", "--diff-filter=U"))
    assert.ok(conflicts.length, result.stderr || "Cherry-pick failed without a resolvable conflict")
    git("cherry-pick", "--abort")
    assert.ok(
      !conflicts.some((file) => controls.some((control) => file === control || file.startsWith(`${control}/`))),
      `Publication control conflict: ${conflicts.join(", ")}`,
    )
    writeFileSync(
      path.join(directory, "replay.json"),
      JSON.stringify({ patches, pending: input.commits.slice(patches.length), conflicts }, null, 2),
    )
    process.exit(0)
  }
  // Replay is mechanical evidence, never a substitute for the semantic review report.
  writeFileSync(path.join(directory, "replay.json"), JSON.stringify({ patches, pending: [], conflicts: [] }, null, 2))
} else if (command === "accept") {
  const input = read(path.join(directory, "input.json"))
  assert.equal(sha(input.old), sha(process.env.SOURCE_SHA))
  git("fetch", "https://github.com/anomalyco/opencode.git", "dev")
  git("merge-base", "--is-ancestor", sha(input.upstream), "FETCH_HEAD")
  assert.deepEqual(stack(input), lines(git("rev-list", "--reverse", `${input.upstream}..${input.old}`)).sort())
  git("bundle", "verify", path.join(directory, "candidate.bundle"))
  git("fetch", path.join(directory, "candidate.bundle"), "refs/heads/nightly-candidate")
  const candidate = git("rev-parse", "FETCH_HEAD")
  git("merge-base", "--is-ancestor", input.upstream, candidate)
  assert.equal(
    git("rev-list", "--merges", `${input.upstream}..${candidate}`),
    "",
    "Candidate must be a linear patch stack",
  )
  const base = git("merge-base", input.old, input.upstream)
  for (const file of lines(git("diff", "--name-only", input.old, candidate, "--", ...controls))) {
    // Carry upstream-only control changes, but never accept agent-authored workflows.
    assert.equal(git("diff", "--name-only", base, input.old, "--", file), "", `Fork control conflict: ${file}`)
    assert.equal(
      git("diff", "--name-only", input.upstream, candidate, "--", file),
      "",
      `Publication control changed: ${file}`,
    )
  }
  const report = read(path.join(directory, "report.json"))
  assert.ok(typeof report.summary === "string" && report.summary.trim())
  assert.ok(
    Array.isArray(report.tests) && report.tests.length && report.tests.every((x) => typeof x === "string" && x.trim()),
  )
  assert.ok(Array.isArray(report.patches))
  assert.deepEqual(
    report.patches.map((p) => p.old).sort(),
    [...input.commits].sort(),
    "Every old patch needs exactly one decision",
  )
  const mapped = report.patches.flatMap((p) => {
    assert.ok(["keep", "adapt", "drop"].includes(p.action))
    assert.ok(typeof p.reason === "string" && p.reason.trim())
    assert.ok(Array.isArray(p.commits))
    assert.equal(p.commits.length === 0, p.action === "drop")
    return p.commits.map(sha)
  })
  assert.deepEqual(
    [...new Set(mapped)].sort(),
    lines(git("rev-list", `${input.upstream}..${candidate}`)).sort(),
    "Every new commit needs provenance",
  )
  const staging = `refs/heads/nightly-${process.env.GITHUB_RUN_ID}`
  assert.match(staging, /^refs\/heads\/nightly-\d+$/)
  git("push", "origin", `${candidate}:${staging}`)
  appendFileSync(process.env.GITHUB_OUTPUT, `candidate=${candidate}\nold=${input.old}\nupstream=${input.upstream}\n`)
} else if (command === "relock") {
  // package.json is the authority for the dependency graph and bun.lock is derived from it,
  // so regenerate the lockfile here with the candidate's own pinned Bun. A dependency bump
  // upstream then costs a commit instead of a text conflict the reviewing agent must refuse.
  const candidate = sha(process.env.FORK_CANDIDATE)
  const tree = path.join(directory, "relock")
  const gitIn = (...args) => execFileSync("git", args, { cwd: tree, encoding: "utf8" }).trim()
  const bun = (...args) => execFileSync("bun", args, { cwd: tree, stdio: "inherit" })
  git("worktree", "add", "--detach", tree, candidate)
  try {
    bun("install", "--lockfile-only")
    if (gitIn("status", "--porcelain", "--", "bun.lock")) {
      gitIn("add", "bun.lock")
      gitIn(
        "-c", "commit.gpgsign=false",
        "-c", "user.name=github-actions[bot]",
        "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
        "commit", "-m", derivedSubject,
      )
    }
    const amended = gitIn("rev-parse", "HEAD")
    if (amended !== candidate) {
      // Prove the regenerated lockfile is reproducible before it can be published.
      bun("install", "--frozen-lockfile", "--ignore-scripts")
      git("push", "origin", `+${amended}:refs/heads/nightly-${process.env.GITHUB_RUN_ID}`)
    }
    appendFileSync(process.env.GITHUB_OUTPUT, `candidate=${amended}\n`)
  } finally {
    git("worktree", "remove", "--force", tree)
  }
} else if (command === "promote") {
  const old = sha(process.env.FORK_OLD)
  const candidate = sha(process.env.FORK_CANDIDATE)
  const upstream = sha(process.env.FORK_UPSTREAM)
  git("fetch", "origin", candidate, old)
  git("merge-base", "--is-ancestor", upstream, candidate)
  const current = git("ls-remote", "origin", branch).split("\t")[0]
  // Retrying publication after a successful promotion must not overwrite newer work.
  if (current !== candidate) {
    assert.equal(current, old, "Fork advanced during this nightly; retry against the new tip")
    const archive = `refs/tags/fork-backup-${old}`
    git(
      "push",
      "--atomic",
      `--force-with-lease=${branch}:${old}`,
      "origin",
      `${old}:${archive}`,
      `${candidate}:${branch}`,
    )
  }
  assert.equal(git("ls-remote", "origin", branch).split("\t")[0], candidate)
} else {
  throw new Error("Usage: nightly.mjs prepare|replay|accept|relock <directory>, or promote")
}
